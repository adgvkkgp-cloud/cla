// Помощники корпуса телосложения.
//
// Строка раздела: [имя, определение, теги?, пол?]
//   определение — строка (свободное определение) или узел:
//     G(род, отличие, пояснение?) — вид: описание собирается из рода и отличия;
//     B(род, текст)               — основание деления: карточка-пояснение,
//                                   виды цепляются к ней, а не к роду;
//     P(целое, текст)             — часть: текст свой, связь с целым проверяется;
//     M(предмет, текст)           — размер: текст свой, связь с предметом проверяется.
//   Род вида — имя позиции или основания; «Имя|голова» задаёт, как род
//   называется в начале определения, если имя для этого не годится.
//   теги — строка через запятую; пол — "male" | "female" | "any".

const G = (genus, diff, note) => ({ k: "G", genus, diff, note });
const B = (genus, text) => ({ k: "B", genus, text });
const P = (whole, text) => ({ k: "P", whole, text });
const M = (of, text) => ({ k: "M", of, text });

// Раздел: o.cat — "natural" | "enhanced", o.g — пол позиций по умолчанию.
const sec = (id, title, subtitle, icon, color, rows, o = {}) =>
  ({ id, title, subtitle, icon, color, category: o.cat || "natural", gender: o.g || "any", rows });

module.exports = { G, B, P, M, sec };
