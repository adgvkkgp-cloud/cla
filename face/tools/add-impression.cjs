function build(section) {
  return [
    "      {",
    `        id: ${JSON.stringify(section.id)},`,
    `        title: ${JSON.stringify(section.title)},`,
    `        subtitle: ${JSON.stringify(section.subtitle)},`,
    `        color: ${JSON.stringify(section.color)},`,
    "        entries: [",
    ...mk(section.rows),
    "        ]",
    "      },",
  ].join("\n");
}

function main() {
  let src = fs.readFileSync(DATA, "utf8");

  // Якорь — последний раздел части XV. Вставка идёт сразу за ним,
  // внутрь той же части.
  const anchor = '        id: "photogenic-angles",';
  const at = src.indexOf(anchor);
  if (at === -1) {
    console.error("Не найден раздел photogenic-angles — якорь вставки.");
    process.exit(1);
  }
  // конец этого раздела: строка "      }," после его entries
  const endMark = "\n      },\n";
  const end = src.indexOf(endMark, at);
  if (end === -1) {
    console.error("Не найден конец раздела photogenic-angles.");
    process.exit(1);
  }
  const cut = end + endMark.length;

  for (const s of SECTIONS) {
    if (src.includes(`id: ${JSON.stringify(s.id)},`)) {
      console.error(`Раздел ${s.id} уже есть — вставка отменена.`);
      process.exit(1);
    }
  }

  const added = SECTIONS.map(build).join("\n") + "\n";
  src = src.slice(0, cut) + added + src.slice(cut);
  fs.writeFileSync(DATA, src);

  const n = SECTIONS.reduce((a, s) => a + s.rows.length, 0);
  console.log(`Добавлено разделов: ${SECTIONS.length}, позиций: ${n}`);
}

main();
