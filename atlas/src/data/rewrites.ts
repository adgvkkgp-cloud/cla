import type { Section } from "./sections";

// ════════════════════════════════════════════════════════════
// ЭТАП 6: ПЕРЕПИСЫВАНИЕ КОРОТКИХ ОПИСАНИЙ
//
// Медиана длины описания по корпусу — 46 знаков, но в старых
// разделах она падает до 8–20. Такие описания не сообщают
// ничего сверх заголовка: «Фактор O», «Фасета C», «Младенчество»,
// «Стадия знакомства». Позиция при этом занимает место в выдаче
// и в поиске и выглядит наполненной.
//
// Здесь описание заменяется на новое по точному совпадению
// заголовка — тем же способом, каким механизм и грани пола
// дописываются в `details.ts` и `facets.ts`.
//
// Две проверки роняют сборку:
//   1. заголовок не найден — опечатка иначе молча ничего
//      не сделает;
//   2. новое описание не длиннее старого — переписывание,
//      не добавляющее содержания, бессмысленно и почти всегда
//      означает недосмотр.
//
// Заголовки при этом не трогаются: переписывается только
// описание, и позиция остаётся на своём месте.
// ════════════════════════════════════════════════════════════

export type RewriteTable = Record<string, Record<string, string>>;

export function applyRewrites(sections: Section[], tables: RewriteTable[]): void {
  const missing: string[] = [];
  const notLonger: string[] = [];
  for (const table of tables) {
    for (const [sectionId, rows] of Object.entries(table)) {
      const section = sections.find((s) => s.id === sectionId);
      if (!section) { missing.push(`раздел ${sectionId}`); continue; }
      for (const [title, text] of Object.entries(rows)) {
        const entry = section.entries.find((e) => e.title === title);
        if (!entry) { missing.push(`${sectionId} :: «${title}»`); continue; }
        if (text.length <= (entry.description || "").length) {
          notLonger.push(`${sectionId} :: «${title}» (${(entry.description || "").length} → ${text.length})`);
          continue;
        }
        entry.description = text;
      }
    }
  }
  if (missing.length) {
    throw new Error(
      "Переписывание не привязано — заголовок не найден (" + missing.length + "):\n  " +
      missing.slice(0, 20).join("\n  "),
    );
  }
  if (notLonger.length) {
    throw new Error(
      "Новое описание не длиннее прежнего (" + notLonger.length + "):\n  " +
      notLonger.slice(0, 20).join("\n  "),
    );
  }
}

