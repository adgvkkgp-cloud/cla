// ════════════════════════════════════════════════════════════
// ЭТАП 4: ГРАНИ ПОЛА
//
// Поля `male` и `female` заполнены на доли процента корпуса,
// при том что вьюер даёт по ним отдельный режим. Здесь они
// дописываются к уже существующим позициям по совпадению
// заголовка — так же, как механизм в `details.ts`.
//
// Правило заполнения одно и оно жёсткое:
//
//   1. Поле заполняется только там, где различие
//      задокументировано. Называется направление и величина —
//      «выше на 10–15 см», «вдвое чаще», «разрыв около 10 %».
//      Направление без величины почти ничего не сообщает.
//   2. Там, где различия нет, где оно мало по сравнению
//      с разбросом внутри пола или где оно оспаривается,
//      поле остаётся пустым — и это честный ответ, а не
//      пробел. Придумывать различие, чтобы заполнить поле,
//      нельзя.
//   3. Позиции о самой изменчивости, о совпадении диапазонов
//      и об осторожности обобщений полей не получают:
//      они говорят не о различии, а о том, как его читать.
//
// Промах по заголовку роняет сборку.
// ════════════════════════════════════════════════════════════

export type Facet = { m?: string; f?: string };
export type FacetTable = Record<string, Record<string, Facet>>;

export function applyFacets(sections: Section[], tables: FacetTable[]): void {
  const missing: string[] = [];
  const empty: string[] = [];
  for (const table of tables) {
    for (const [sectionId, rows] of Object.entries(table)) {
      const section = sections.find((s) => s.id === sectionId);
      if (!section) { missing.push(`раздел ${sectionId}`); continue; }
      for (const [title, facet] of Object.entries(rows)) {
        const entry = section.entries.find((e) => e.title === title);
        if (!entry) { missing.push(`${sectionId} :: «${title}»`); continue; }
        if (!facet.m && !facet.f) { empty.push(`${sectionId} :: «${title}»`); continue; }
        if (facet.m) entry.male = facet.m;
        if (facet.f) entry.female = facet.f;
      }
    }
  }
  if (missing.length) {
    throw new Error(
      "Грань пола не привязана — заголовок не найден (" + missing.length + "):\n  " +
      missing.slice(0, 20).join("\n  "),
    );
  }
  if (empty.length) {
    throw new Error(
      "Пустая грань пола — позицию следует не перечислять вовсе (" + empty.length + "):\n  " +
      empty.slice(0, 20).join("\n  "),
    );
  }
}

