// СИСТЕМАТИКА: РОД, ВИД, ОСНОВАНИЕ ДЕЛЕНИЯ
//
// Определение строится как ближайший род + видовое отличие:
//   «Абсолютная монархия — монархия, в которой власть монарха
//    не ограничена ни конституцией, ни представительным органом».
// Род здесь — родительская позиция, видовое отличие — поле diff,
// продолжающее род грамматически. Вьюер собирает определение сам,
// поэтому при переименовании рода определения не расходятся.
//
// Отношений два, и их нельзя смешивать:
//
//   вид   — деление понятия: монархия есть форма правления.
//           Монархия → абсолютная, ограниченная.
//   часть — расчленение целого: форма правления не есть форма
//           государства, а её сторона. Форма государства →
//           форма правления, форма устройства, политический режим.
//
// Деление всегда идёт по основанию — признаку, по которому виды
// различаются: монархии делятся по объёму власти монарха, по порядку
// замещения престола, по соединению светской и духовной власти.
// Оснований у одного понятия может быть несколько — это разные
// деления одного рода, а не одно деление с пересекающимися членами.
//
// Ещё две служебные роли:
//
//   основание — позиция, которая описывает само деление
//               («Основание деления монархий»). Раньше она стояла
//               в списке соседом своих видов; теперь она — узел,
//               под которым виды и висят.
//   признаки  — позиция «Признаки федерации»: не понятие, а перечень
//               признаков другого понятия; крепится к нему.
//
// home — ссылка на основное место понятия. Одно понятие живёт во
// многих разделах; дерево у него одно, остальные места ссылаются туда.
//
// Сборку роняют:
//   • родитель, основание или дом не найдены;
//   • цикл по родителям;
//   • вид без основания или без видового отличия;
//   • деление, в котором меньше двух видов: один вид — не деление;
//   • позиция «основание», которой не соответствует деление;
//   • для раздела, отмеченного как систематизированный целиком, —
//     хотя бы одна позиция вне дерева.
//
// Чего механически проверить нельзя и что держится на разборе:
// соразмерность деления (виды в сумме дают род), исключаемость членов
// (виды не пересекаются) и непрерывность (нет пропущенных ступеней).
// ════════════════════════════════════════════════════════════

type Node =
  | { genus: string; by: string; diff: string }   // вид
  | { whole: string; by: string }                 // часть
  | { basisOf: string; by: string }               // основание
  | { signsOf: string };                          // признаки

export type TreeTable = Record<string, { complete?: boolean; nodes: Record<string, Node> }>;
export type HomeTable = Record<string, Record<string, [string, string]>>;

export function applyTree(sections: Section[], trees: TreeTable[], homes: HomeTable[]): void {
  const errs: string[] = [];
  const secById = new Map(sections.map((s) => [s.id, s]));
  const find = (s: Section, t: string) => s.entries.find((e) => e.title === t);

  for (const table of trees) {
    for (const [sid, spec] of Object.entries(table)) {
      const sec = secById.get(sid);
      if (!sec) { errs.push(`раздел ${sid} не найден`); continue; }
      const where = (t: string) => `${sid} :: «${t}»`;

      let ord = 0;
      for (const [title, n] of Object.entries(spec.nodes)) {
        const e = find(sec, title);
        if (!e) { errs.push(`${where(title)}: позиция не найдена`); continue; }
        e.o = ++ord;
        const link = (up: string) => { if (!find(sec, up)) errs.push(`${where(title)}: родитель «${up}» не найден`); return up; };
        if ("genus" in n) {
          if (!n.by) errs.push(`${where(title)}: вид без основания деления`);
          if (!n.diff || !n.diff.trim()) errs.push(`${where(title)}: вид без видового отличия`);
          Object.assign(e, { up: link(n.genus), rel: "вид", by: n.by, diff: n.diff });
        } else if ("whole" in n) {
          Object.assign(e, { up: link(n.whole), rel: "часть", by: n.by });
        } else if ("basisOf" in n) {
          Object.assign(e, { up: link(n.basisOf), rel: "основание", by: n.by });
        } else if ("signsOf" in n) {
          Object.assign(e, { up: link(n.signsOf), rel: "признаки" });
        }
      }

      // Циклы по родителям.
      for (const e of sec.entries) {
        const seen = new Set<string>(); let cur: Entry | undefined = e;
        while (cur && cur.up) {
          if (seen.has(cur.title)) { errs.push(`${where(e.title)}: цикл по родителям`); break; }
          seen.add(cur.title); cur = find(sec, cur.up);
        }
      }

      // Деления: (род, основание) → виды; в каждом не меньше двух.
      const div = new Map<string, string[]>();
      for (const e of sec.entries) if (e.rel === "вид") {
        const k = e.up + "\u0000" + e.by; div.set(k, [...(div.get(k) || []), e.title]);
      }
      for (const [k, members] of div) if (members.length < 2) {
        const [g, by] = k.split("\u0000");
        errs.push(`${sid} :: «${g}», деление «${by}»: один вид (${members[0]}) — это не деление`);
      }
      // Позиция-основание должна описывать существующее деление или группу частей.
      for (const e of sec.entries) if (e.rel === "основание") {
        const has = sec.entries.some((x) => x.up === e.up && x.by === e.by && (x.rel === "вид" || x.rel === "часть"));
        if (!has) errs.push(`${where(e.title)}: основание «${e.by}» не описывает ни одного деления «${e.up}»`);
      }
      // Раздел, систематизированный целиком: всё в дереве.
      if (spec.complete) {
        const placed = (e: Entry) => !!e.up || sec.entries.some((x) => x.up === e.title);
        for (const e of sec.entries) if (!placed(e)) errs.push(`${where(e.title)}: вне дерева в разделе, отмеченном как систематизированный`);
      }
    }
  }

  for (const table of homes) {
    for (const [sid, rows] of Object.entries(table)) {
      const sec = secById.get(sid);
      if (!sec) { errs.push(`раздел ${sid} не найден (дом)`); continue; }
      for (const [title, [hs, ht]] of Object.entries(rows)) {
        const e = find(sec, title);
        if (!e) { errs.push(`${sid} :: «${title}»: позиция не найдена (дом)`); continue; }
        const hsec = secById.get(hs);
        const target = hsec && find(hsec, ht);
        if (!target) { errs.push(`${sid} :: «${title}»: дом ${hs} :: «${ht}» не найден`); continue; }
        if (!target.up && !hsec!.entries.some((x) => x.up === ht)) errs.push(`${sid} :: «${title}»: дом «${ht}» не стоит в дереве`);
        if (e.up) errs.push(`${sid} :: «${title}»: у позиции уже есть место в дереве, дом ей не нужен`);
        e.home = { s: hs, t: ht };
      }
    }
  }

  if (errs.length) {
    throw new Error("Систематика не сходится (" + errs.length + "):\n  " + errs.slice(0, 30).join("\n  "));
  }
}

