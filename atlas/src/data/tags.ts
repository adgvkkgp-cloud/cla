import type { Section } from "./sections";

// ════════════════════════════════════════════════════════════
// ЭТАП 1: ЯРЛЫКИ
//
// Поле `tag` в схеме было всегда, но не заполнялось ни разу —
// а вьюер показывает по нему фильтр. Здесь ярлык проставляется
// при сборке, правилами, а не руками по позициям.
//
// Порядок применения: сочетание → правило раздела → правило
// позиции. Первое сработавшее выигрывает, ярлык у позиции один.
// Непомеченная позиция — это нормально: ярлык ставится там, где
// он сужает выдачу осмысленно, а не ради заполненности.
// ════════════════════════════════════════════════════════════

// Разделы, целиком собранные перебором: один список объектов,
// умноженный на несколько отношений. Их 15 и в них 17 519 позиций —
// почти 39 % корпуса. Ярлык нужен, чтобы их можно было убрать
// из выдачи одним щелчком, не удаляя из данных.
export const comboSections: string[] = [
  "tr-likes", "tr-disp-love", "tr-disp-interest", "tr-disp-indiff",
  "tr-disp-fear", "tr-disp-dislike", "tr-disp-addict",
  "tr-mimic-gen", "tr-app-gen", "tr-voice-gen", "tr-body-gen",
  "tr-degree", "tr-talents", "y-philias", "y-manias",
];

// Правила по названию раздела: весь раздел однороден по жанру.
export const sectionRules: [RegExp, string][] = [
  [/фоби|\bмани[ияй]|синдром|расстройств|нарушени|патопсихолог|психиатр|девиантн|зависимост|аддикц|болезн|симптоматолог/i, "патология"],
  [/классификац|^виды\b|\bвиды и\b|^типы\b|типологи|^формы\b|разновидност|^объекты/i, "классификация"],
  [/латинск/i, "латынь"],
  [/школы|^философские направлени|социологические теории|этические теории|экономические школы|парадигм|-измы|направлени/i, "направление"],
  [/именны|концепци \(|\(именные/i, "именное"],
  [/^методы\b|^техники\b|методик/i, "метод"],
  [/^истори|римское право|культурные эпохи|^древн/i, "историческое"],
];

// Правила по заголовку позиции — для разделов смешанного состава.
export const entryRules: [RegExp, string][] = [
  [/^(возражени|критика|несостоятельн|спор о\b|спор об\b|критик)/i, "спорное"],
  [/^(виды|типы|классификац|формы|разновидност|основани деления|деление)\b/i, "классификация"],
  [/синдром|расстройств|\bфоби|галлюцинац|\bбред\b|невроз|психоз|деменц|амнези|агнози|апракси|афази/i, "патология"],
];

export function applyTags(sections: Section[]): void {
  const combo = new Set(comboSections);
  for (const s of sections) {
    let blanket: string | undefined;
    if (combo.has(s.id)) {
      blanket = "сочетание";
    } else {
      for (const [re, tag] of sectionRules) {
        if (re.test(s.title)) { blanket = tag; break; }
      }
    }
    for (const e of s.entries) {
      if (e.tag) continue;
      if (blanket) { e.tag = blanket; continue; }
      for (const [re, tag] of entryRules) {
        if (re.test(e.title)) { e.tag = tag; break; }
      }
    }
  }
}
